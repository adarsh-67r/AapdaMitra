// Copies the modules both clients must answer identically from their canonical
// home in the citizen app into the web app.
//
// Cross-app imports are not an option here: Metro and the Next bundler each
// resolve from their own project root, so a shared file has to physically exist
// in both trees. This is the same arrangement build-district-index.js already
// uses for the district data -- one source, copied, never hand-edited downstream.
//
// Run with: node scripts/sync-shared-lib.js

const fs = require("fs");
const path = require("path");

const FROM = path.join(__dirname, "..", "apps", "citizen-app", "src", "lib");
const TO = path.join(__dirname, "..", "apps", "web", "src", "lib");
const MODULES = ["citizen-summary.ts"];

// The i18n modules are plain TypeScript with no React Native in them, so both
// clients can share them whole. Sharing matters more here than anywhere else:
// a string translated once should be translated for both, and a language
// offered in one client should exist in the other.
const I18N_FROM = path.join(__dirname, "..", "apps", "citizen-app", "src", "lib", "i18n");
const I18N_TO = path.join(__dirname, "..", "apps", "web", "src", "lib", "i18n");

const BANNER =
  "// Generated by scripts/sync-shared-lib.js — edit the citizen-app copy, not this one.\n";

function copyTree(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    // Tests stay with the canonical copy; the web app has no jest setup for
    // them and a duplicated test that nothing runs is worse than none.
    if (entry.name.endsWith(".test.ts") || entry.name.endsWith(".test.tsx")) continue;
    // The provider is React Native — AsyncStorage, expo fonts. Web has its own.
    if (entry.name === "use-language.tsx") continue;
    // A record of which strings the app asks for; only the app's build uses it.
    if (entry.name.startsWith(".")) continue;
    const src = path.join(from, entry.name);
    const dest = path.join(to, entry.name);
    if (entry.isDirectory()) {
      copyTree(src, dest);
    } else {
      fs.writeFileSync(dest, BANNER + fs.readFileSync(src, "utf8"));
      console.log("synced i18n/" + path.relative(I18N_FROM, src).split(path.sep).join("/"));
    }
  }
}

copyTree(I18N_FROM, I18N_TO);

for (const file of MODULES) {
  // The only line that is not portable between the two apps is the geo import:
  // the citizen app has haversineKm next door, the web app has it at
  // @/lib/geo-client. Rewritten during the copy so neither copy needs editing.
  const source = fs
    .readFileSync(path.join(FROM, file), "utf8")
    .replace('from "./geo"', 'from "@/lib/geo-client"');
  fs.writeFileSync(path.join(TO, file), BANNER + source);
  console.log(`synced ${file}`);
}
